const FALLBACK_ATTEMPTS = 500;

/**
 * 挑一个没被占用的成员名：先从名单里随机挑，名单用完后随机组合。都占满时返回 undefined。
 * occupied 包括现有成员、已删除成员和成员文件夹的名字（比较时不区分大小写）；exclude 是「换一个」时要避开的当前名字。
 */
export function suggestMemberName(occupied: Iterable<string>, exclude?: string, random: () => number = Math.random): string | undefined {
	const taken = new Set([...occupied].map(name => name.toLowerCase()));
	if (exclude) taken.add(exclude.toLowerCase());
	const available = MEMBER_NAME_CANDIDATES.filter(name => !taken.has(name.toLowerCase()));
	if (available.length > 0) return available[Math.floor(random() * available.length)];
	const pick = (characters: string) => characters[Math.floor(random() * characters.length)]!;
	for (let attempt = 0; attempt < FALLBACK_ATTEMPTS; attempt++) {
		const name = pick(MEMBER_NAME_SURNAMES) + pick(MEMBER_NAME_GIVEN) + (random() < 0.5 ? pick(MEMBER_NAME_GIVEN) : '');
		if (!taken.has(name)) return name;
	}
	return undefined;
}
